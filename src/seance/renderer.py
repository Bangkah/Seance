from __future__ import annotations

from .evidence import Facts
from .grounding import Claim, GroundingResult
from .text import sanitize

DISCLAIMER = "Generated by a local model from repository text. Verify before trusting."
REFUSAL = "The ghost does not remember that."


def _ids(claim: Claim) -> str:
    return ", ".join(claim.evidence_ids)


def _dates(claim: Claim) -> str:
    return claim.dates[0] if claim.dates else "undated"


def _timeline_text(claim: Claim) -> str:
    text = claim.text
    for date in claim.dates[:1]:
        if text.startswith(date):
            text = text[len(date) :].lstrip(" :-—")
    return text


def _ordered_timeline(result: GroundingResult) -> tuple[Claim, ...]:
    return tuple(
        sorted(result.timeline, key=lambda claim: claim.dates[0] if claim.dates else "9999")
    )


def render_report(
    facts: Facts,
    result: GroundingResult,
    *,
    dropped_evidence: int,
    model: str,
) -> str:
    lines: list[str] = [f"AUTOPSY: {facts.repo_name}"]
    if facts.first is not None:
        lines.append(f"  Born : {facts.first.iso_date} (C:{facts.first.short})")
    if facts.last is not None:
        lines.append(f"  Died : {facts.last.iso_date} (C:{facts.last.short})  [last commit]")
    if facts.gap_months is not None:
        lines.append(f"  Gap  : {facts.gap_months} months since the last commit")
    lines.append(
        f"  Size : {facts.total_commits} commits, {len(facts.authors)} authors, "
        f"{len(facts.tags)} tags"
    )
    lines.append("")

    if result.summary is not None:
        lines.extend(["What it was", f"  {result.summary.text} [{_ids(result.summary)}]", ""])
    if result.purpose is not None:
        lines.extend(["Why it existed", f"  {result.purpose.text} [{_ids(result.purpose)}]", ""])

    if result.timeline:
        lines.append("Timeline")
        for claim in _ordered_timeline(result):
            lines.append(f"  {_dates(claim):<10}  {_timeline_text(claim)} [{_ids(claim)}]")
        lines.append("")

    if result.hypotheses:
        lines.append("Cause of death (hypotheses, not facts)")
        for index, claim in enumerate(result.hypotheses, start=1):
            lines.append(f"  {index}. {claim.text} [{_ids(claim)}]  confidence: {claim.confidence}")
        lines.append("")

    if result.revival:
        lines.append("Revival steps (suggestions, not guarantees)")
        for index, claim in enumerate(result.revival, start=1):
            lines.append(f"  {index}. {claim.text} [{_ids(claim)}]")
        lines.append("")

    lines.append(f"{result.dropped} claims dropped for lacking evidence.")
    if dropped_evidence:
        lines.append(f"{dropped_evidence} evidence items omitted to fit the context budget.")
    lines.append(f"Model: {model}, local. {DISCLAIMER}")
    return sanitize("\n".join(lines))


def render_report_markdown(
    facts: Facts,
    result: GroundingResult,
    *,
    dropped_evidence: int,
    model: str,
) -> str:
    lines: list[str] = [f"# Autopsy: {facts.repo_name}", ""]
    if facts.first is not None:
        lines.append(f"- **First commit:** {facts.first.iso_date} (`{facts.first.short}`)")
    if facts.last is not None:
        lines.append(f"- **Last commit:** {facts.last.iso_date} (`{facts.last.short}`)")
    if facts.gap_months is not None:
        lines.append(f"- **Silence:** {facts.gap_months} months")
    lines.append(
        f"- **Size:** {facts.total_commits} commits, {len(facts.authors)} authors, "
        f"{len(facts.tags)} tags"
    )
    lines.append("")

    if result.summary is not None:
        lines.extend(
            ["## What it was", "", result.summary.text, "", f"Evidence: {_ids(result.summary)}", ""]
        )
    if result.purpose is not None:
        lines.extend(
            [
                "## Why it existed",
                "",
                result.purpose.text,
                "",
                f"Evidence: {_ids(result.purpose)}",
                "",
            ]
        )

    if result.timeline:
        lines.extend(["## Timeline", ""])
        for claim in _ordered_timeline(result):
            lines.append(f"- **{_dates(claim)}** — {_timeline_text(claim)} (`{_ids(claim)}`)")
        lines.append("")

    if result.hypotheses:
        lines.extend(["## Cause of death (hypotheses, not facts)", ""])
        for claim in result.hypotheses:
            lines.append(f"- {claim.text} (`{_ids(claim)}`) — confidence: {claim.confidence}")
        lines.append("")

    if result.revival:
        lines.extend(["## Revival steps (suggestions, not guarantees)", ""])
        for claim in result.revival:
            lines.append(f"- {claim.text} (`{_ids(claim)}`)")
        lines.append("")

    lines.append(f"_{result.dropped} claims dropped for lacking evidence._")
    if dropped_evidence:
        lines.append(f"_{dropped_evidence} evidence items omitted to fit the context budget._")
    lines.extend(["", f"Model: `{model}` running locally. {DISCLAIMER}"])
    return sanitize("\n".join(lines))


def render_answer(claim: Claim | None) -> str:
    if claim is None:
        return REFUSAL
    return f"{claim.text} [{_ids(claim)}]"
